// claw_loader_selftest.c — TEMPORARY. Exercises the real, promoted
// claw_loader module (source/modules/claw_loader/) end-to-end: resolving
// BOTH claw_personal_init/claw_personal_deinit by name (rounds 1-3 of the
// R&D spike this was promoted from only ever resolved one entry symbol at
// a time), calling init(), then deinit(), then unloading.
//
// guest3_o_bytes is a standalone compile of:
//
//   static int s_init_count = 0;
//   static const char tag[] = "loaded-ok";
//   int claw_personal_init(void) {
//       s_init_count++;
//       return (int)tag[0] + s_init_count;   // 'l' (108) + 1 = 109 on first call
//   }
//   void claw_personal_deinit(void) { s_init_count = 0; }
//
// Compiled: xtensa-esp32s3-elf-gcc -mtext-section-literals -mlongcalls -O0 -c
//
// guest4_o_bytes (below, second test) closes the gap this file's own
// comment used to note here: a loaded module calling a REAL host function
// BY NAME (purr_kernel_uptime_ms(), resolved via claw_loader.c's import
// table / claw_elf.h's CLAW_SEC_EXTERN — piece 1 of the "named-host-
// function import table" work), not through a parameter it was handed
// (round 2's callback trick already proved that path). It's a standalone
// compile of:
//
//   #include <stdint.h>
//   extern uint64_t purr_kernel_uptime_ms(void);
//   static uint64_t s_last_uptime = 0;
//   int claw_personal_init(void) {
//       s_last_uptime = purr_kernel_uptime_ms();
//       return (int)(s_last_uptime & 0x7fffffff);
//   }
//   void claw_personal_deinit(void) { s_last_uptime = 0; }
//
// Compiled: xtensa-esp32s3-elf-gcc -mtext-section-literals -mlongcalls -O0 -c
// objdump -r confirmed a R_XTENSA_32 relocation in .text pointing at the
// UNDEFINED symbol "purr_kernel_uptime_ms" (SHN_UNDEF) — exactly the case
// claw_elf.c's resolve_import() exists to handle — plus an
// R_XTENSA_ASM_EXPAND entry at the l32r site, which (like R_XTENSA_SLOT0_OP)
// the parser correctly ignores: only R_XTENSA_32 entries are ever collected
// as patches.
//
// purr_win_create()-style calls still go through purr_kernel_ui() (a
// function-pointer struct behind ANOTHER named external symbol) — reaching
// those needs purr_kernel_ui() itself added to the import table, not a
// further loader change. Not needed for this selftest to prove the
// mechanism end-to-end.
//
// run3() (third test, below) exercises piece 2 — personal-space storage
// (claw_loader_personal_add/count/at/load/remove) — reusing guest3_o_bytes
// rather than compiling yet another guest object, since this test isn't
// about relocation/import behavior at all, just the SD file plumbing
// around an already-proven loadable object.
//
// run4() (fourth test, below) exercises piece 3 — the app_manager
// integration (APP_TIER_PERSONAL, app_manager_scan_ex()'s personal-app
// scan block, launch_personal()) — through app_manager's real PUBLIC API
// (app_manager_scan/count/get/launch_by_name/stop), not by calling
// claw_loader directly. This needed a NEW guest object: guest3's
// claw_personal_init() deliberately returns 109 to prove claw_loader_load()
// itself works, but native_task() (app_manager.c) treats any nonzero
// init() return as APP_STATE_ERROR — a personal app dispatched through the
// real launch path needs to actually report success (0) the way a real app
// would. guest5_o_bytes is a standalone compile of:
//
//   static int s_init_calls = 0;
//   int claw_personal_init(void) { s_init_calls++; return 0; }
//   void claw_personal_deinit(void) { s_init_calls = 0; }
//
// Compiled: xtensa-esp32s3-elf-gcc -mtext-section-literals -mlongcalls -O0 -c
//
// run4() also creates a throwaway user_mgr account ("selftest_user") to
// scan/launch under — since APP_TIER_PERSONAL apps are only ever scanned
// for the CURRENTLY LOGGED IN user (see app_manager_scan_ex()'s own
// comment) — and saves/restores whatever real session was active before
// the test, so it never leaves a real device logged out (or logged into a
// throwaway account) just from having run once.

