// claw_loader_selftest_run4() — piece 3: the app_manager integration.
// Exercises the REAL public API (app_manager_scan/count/get/
// launch_by_name/stop), under a throwaway user_mgr account this creates
// and removes, restoring whatever real session was active beforehand.
void claw_loader_selftest_run4(void)
{
    static const char *user = "selftest_user";
    static const char *app  = "selftest_app4";

    char prev_user[USER_MGR_USERNAME_MAX + 1] = {0};
    bool was_logged_in = user_mgr_is_logged_in();
    if (was_logged_in) {
        strncpy(prev_user, user_mgr_current_user(), sizeof(prev_user) - 1);
    }
    ESP_LOGI(TAG, "run4: was_logged_in=%d prev_user='%s'", was_logged_in, prev_user);

    bool have_account = user_mgr_exists(user) || user_mgr_create(user, NULL);
    bool logged_in = have_account && user_mgr_set_logged_in(user);
    ESP_LOGI(TAG, "run4: have_account=%d logged_in=%d", have_account, logged_in);

    bool pass = false;
    if (logged_in) {
        bool added = claw_loader_personal_add(user, app, guest5_o_bytes, sizeof(guest5_o_bytes));
        ESP_LOGI(TAG, "run4: personal_add = %d", added);

        int found_count = app_manager_scan();
        ESP_LOGI(TAG, "run4: app_manager_scan() = %d apps total", found_count);

        int idx = -1;
        for (int i = 0; i < app_manager_count(); i++) {
            const app_entry_t *e = app_manager_get(i);
            if (e && strcmp(e->name, app) == 0) { idx = i; break; }
        }
        ESP_LOGI(TAG, "run4: found in registry at idx=%d", idx);

        if (idx >= 0) {
            const app_entry_t *e0 = app_manager_get(idx);
            ESP_LOGI(TAG, "run4: tier=%d (expect APP_TIER_PERSONAL=%d) path='%s'",
                     (int)e0->tier, (int)APP_TIER_PERSONAL, e0->path);

            int rc = app_manager_launch_by_name(app);
            // native_task() runs asynchronously on its own task — give it a
            // moment to actually call init() and report state, same as any
            // other async native app launch.
            vTaskDelay(pdMS_TO_TICKS(300));
            const app_entry_t *e1 = app_manager_get(idx);
            app_state_t st1 = e1 ? e1->state : APP_STATE_ERROR;
            ESP_LOGI(TAG, "run4: launch rc=%d, state after=%d (expect RUNNING=%d) error='%s'",
                     rc, (int)st1, (int)APP_STATE_RUNNING, e1 ? e1->error : "?");

            app_manager_stop(idx);
            const app_entry_t *e2 = app_manager_get(idx);
            app_state_t st2 = e2 ? e2->state : APP_STATE_ERROR;
            ESP_LOGI(TAG, "run4: state after stop=%d (expect STOPPED=%d)", (int)st2, (int)APP_STATE_STOPPED);

            pass = (e0->tier == APP_TIER_PERSONAL) && (rc == 0) &&
                   (st1 == APP_STATE_RUNNING) && (st2 == APP_STATE_STOPPED);
        }

        claw_loader_personal_remove(user, app);
    }

    // Clean up: remove the throwaway account (also logs it out per
    // user_mgr_remove()'s own contract), then restore whatever was logged
    // in before, if anything.
    user_mgr_remove(user);
    if (was_logged_in && prev_user[0]) {
        bool restored = user_mgr_set_logged_in(prev_user);
        ESP_LOGI(TAG, "run4: restored previous session '%s' = %d", prev_user, restored);
    }

    ESP_LOGI(TAG, "run4: %s", pass ? "SELFTEST PASS" : "SELFTEST FAIL");
}
