static const catcall_display_t *s_disp = NULL;
static int s_scr_w = 0, s_scr_h = 0;

static void draw_char(int px, int py, char c, uint16_t fg)
{
    if (c < 0x20 || c > 0x7E) c = ' ';
    const uint8_t *glyph = s_font6x8[(unsigned char)c - 0x20];
    uint16_t buf[FONT_W * FONT_H];
    for (int cx = 0; cx < FONT_W; cx++) {
        uint8_t bits = glyph[cx];
        for (int cy = 0; cy < FONT_H; cy++) {
            buf[cy * FONT_W + cx] = (bits & (1 << cy)) ? fg : BG_COLOR;
        }
    }
    s_disp->push_pixels(px, py, FONT_W, FONT_H, buf);
}

static void draw_str(int px, int py, const char *s, uint16_t fg)
{
    while (*s) {
        draw_char(px, py, *s, fg);
        px += FONT_W;
        s++;
    }
}

// Clears a field's drawing area (label width fixed, value area cleared
// fresh each redraw so a shorter new value doesn't leave old glyphs
// trailing after it — same reasoning boot_splash.c's own status-line
// clear-then-redraw already documents).
static void clear_row(int py, int w)
{
    s_disp->fill_rect(0, py, w, FONT_H, BG_COLOR);
}

#define ROW_TITLE  1
#define ROW_MOTD   2
#define ROW_USER   4
#define ROW_PASS   5
#define ROW_STATUS 7

static void redraw(const login_core_t *lc)
{
    int y_user   = ROW_USER  * FONT_H;
    int y_pass   = ROW_PASS  * FONT_H;
    int y_status = ROW_STATUS * FONT_H;

    clear_row(y_user, s_scr_w);
    clear_row(y_pass, s_scr_w);
    clear_row(y_status, s_scr_w);

    char line[LOGIN_USERNAME_MAX + 16];
    int n = 0;
    const char *p = "login: ";
    while (*p) line[n++] = *p++;
    p = lc->username;
    while (*p) line[n++] = *p++;
    if (lc->state == LOGIN_STATE_USERNAME) line[n++] = '_';
    line[n] = '\0';
    draw_str(FONT_W, y_user, line, FG_COLOR);

    if (lc->state == LOGIN_STATE_PASSWORD || lc->state == LOGIN_STATE_ERROR ||
        lc->state == LOGIN_STATE_SUCCESS) {
        n = 0;
        p = "password: ";
        while (*p) line[n++] = *p++;
        for (int i = 0; i < lc->p_len; i++) line[n++] = '*';
        if (lc->state == LOGIN_STATE_PASSWORD) line[n++] = '_';
        line[n] = '\0';
        uint16_t pw_color = (lc->state == LOGIN_STATE_ERROR) ? ERR_COLOR : FG_COLOR;
        draw_str(FONT_W, y_pass, line, pw_color);
    }

    if (lc->state == LOGIN_STATE_ERROR && lc->error_msg) {
        draw_str(FONT_W, y_status, lc->error_msg, ERR_COLOR);
    } else if (lc->state == LOGIN_STATE_SUCCESS) {
        draw_str(FONT_W, y_status, "Login successful.", FG_COLOR);
    }
}

bool login_render_init(void)
{
    s_disp = purr_kernel_display();
    if (!s_disp || !s_disp->get_info || !s_disp->fill_rect || !s_disp->push_pixels) return false;

    display_info_t info;
    s_disp->get_info(&info);
    s_scr_w = info.width;
    s_scr_h = info.height;
    if (s_scr_w <= 0 || s_scr_h <= 0) return false;

    s_disp->fill_rect(0, 0, s_scr_w, s_scr_h, BG_COLOR);
    draw_str(FONT_W, ROW_TITLE * FONT_H, "Welcome to PURR OS", FG_COLOR);
    return true;
}

// Drawn once, the first call only — lc->motd never changes after
// login_ui_main.c's own load_motd() runs, unlike username/password/state
// which redraw() below repaints on every call.
static bool s_motd_drawn = false;

void login_render_draw(const login_core_t *lc)
{
    if (!s_disp) return;
    if (!s_motd_drawn && lc->motd[0]) {
        draw_str(FONT_W, ROW_MOTD * FONT_H, lc->motd, FG_COLOR);
        s_motd_drawn = true;
    }
    redraw(lc);
}

// Non-blocking-ish: polls every registered input for up to timeout_ms,
// returns a raw keycode byte (ASCII — same convention purr_fbtty.c's own
// fbtty_read_byte() already established: a driver's KEY_DOWN keycode IS
// the ASCII byte, no HID translation layer exists or is needed today), or
// -1 if nothing arrived. Polls ALL registered inputs, not just the first
// — purr_fbtty.c's own comment explains why: a device can register a
// pointer-only input (trackball) before its real keyboard, and the first-
// registered one alone would silently never see a keystroke.
int login_render_poll_key(void)
{
    int count = purr_kernel_input_count();
    if (count <= 0) return -1;
    for (int i = 0; i < count; i++) {
        const catcall_input_t *input = purr_kernel_input_at(i);
        if (!input || !input->poll_event) continue;
        input_event_t ev;
        while (input->poll_event(&ev)) {
            if (ev.type == INPUT_EVENT_KEY_DOWN && ev.keycode > 0 && ev.keycode <= 0xFF) {
                return (int)ev.keycode;
            }
        }
    }
    return -1;
}

