typedef int32_t esp_err_t;

typedef struct {
    uint16_t width;
    uint16_t height;
    uint8_t  bits_per_pixel;
    char     name[32];
} display_info_t;

typedef struct {
    const char *name;
    uint8_t     catcall_version;
    esp_err_t (*init)(const void *cfg);
    esp_err_t (*push_pixels)(int x, int y, int w, int h, const uint16_t *data);
    esp_err_t (*fill_rect)(int x, int y, int w, int h, uint16_t color);
    esp_err_t (*set_brightness)(uint8_t level);
    void      (*get_info)(display_info_t *out);
    esp_err_t (*deinit)(void);
    esp_err_t (*push_pixels_async)(int x, int y, int w, int h, int stride, const uint16_t *data);
    void      (*flush_done_cb)(void (*cb)(void *user), void *user);
} catcall_display_t;

typedef enum {
    INPUT_EVENT_NONE     = 0,
    INPUT_EVENT_KEY_DOWN = 1,
    INPUT_EVENT_KEY_UP   = 2,
    INPUT_EVENT_POINTER  = 3,
} input_event_type_t;

typedef struct {
    input_event_type_t type;
    uint16_t keycode;
    int16_t  delta_x;
    int16_t  delta_y;
    uint8_t  modifiers;
} input_event_t;

typedef struct {
    const char *name;
    uint8_t     catcall_version;
    esp_err_t (*init)(void);
    bool      (*poll_event)(input_event_t *out);
    esp_err_t (*deinit)(void);
    esp_err_t (*set_backlight)(uint8_t brightness);
} catcall_input_t;

extern const catcall_display_t *purr_kernel_display(void);
extern int                      purr_kernel_input_count(void);
extern const catcall_input_t   *purr_kernel_input_at(int idx);

