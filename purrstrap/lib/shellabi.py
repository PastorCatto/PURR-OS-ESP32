"""The shell ABI's list of exports (PurrOS/main/purr_shell_exports.def), as purrstrap needs it to build a loadable shell (plan7.md).

The kernel includes the list as C (purr_shell_abi.c builds the table of real addresses). A shell module is built from ordinary C sources against ordinary
headers, with -mlongcalls, so every call to the OS is `l32r` of a literal followed by `callx8`; the literal is what this module controls: the linker script
made here gives every exported name the placeholder address IMPORT_BASE + 4 * position, so the module's literals hold placeholders, and the loader writes the
real address over each one (the build records where they are with find_imports()). Nothing is mapped at the placeholder addresses on the chip, so a call
that was never patched faults at once instead of running something else.

A name is only ever added at the end of the list; removing or moving one is a new ABI version (purr_shell_abi.h).
"""

import re
import struct

# PURR_SHELL_IMPORT_BASE in purr_shell_abi.h. It is in the same 1 GB region (the top two address bits) as the module's two link addresses (0 and 0x100000):
# the Xtensa windowed `callx8` keeps those bits in the return address, and the linker refuses a call that crosses a region ("windowed longcall crosses 1GB
# boundary"). At run time the module and the kernel are both in the instruction region, so the real calls never cross.
IMPORT_BASE = 0x0F000000
ABI_VERSION = 1                 # PURR_SHELL_ABI_VERSION in purr_shell_abi.h

_LINE = re.compile(r"^\s*SHELL_(FN|DATA)\(\s*(?:([A-Za-z_][A-Za-z0-9_ ]*?)\s*,\s*)?([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*$")


class ShellAbiError(Exception):
    pass


def parse_def(text):
    """The exports in file order: a list of (kind, name, ctype) with kind "fn" or "data" (ctype is None for a function). Comments and blank lines are skipped."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out, seen = [], set()
    for no, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        m = _LINE.match(line)
        if not m:
            raise ShellAbiError("line %d: not SHELL_FN(name) or SHELL_DATA(type, name): %r" % (no, line))
        kind = m.group(1).lower()
        ctype, name = m.group(2), m.group(3)
        if (kind == "data") != (ctype is not None):
            raise ShellAbiError("line %d: SHELL_FN takes a name, SHELL_DATA takes a type and a name: %r" % (no, line))
        if name in seen:
            raise ShellAbiError("line %d: %s is listed twice" % (no, name))
        seen.add(name)
        out.append(("fn" if kind == "fn" else "data", name, ctype))
    if not out:
        raise ShellAbiError("the list is empty")
    return out


def placeholder(index, base=IMPORT_BASE):
    return base + 4 * index


def linker_script(entries, base=IMPORT_BASE):
    """Linker script text that defines every export as its placeholder address (include it with -T next to the module's own script)."""
    lines = ["/* generated by purrstrap/lib/shellabi.py from purr_shell_exports.def: do not edit */"]
    for i, (_kind, name, _ctype) in enumerate(entries):
        lines.append("%s = 0x%08X;" % (name, placeholder(i, base)))
    return "\n".join(lines) + "\n"


def find_imports(blob_a, blob_b, count, base=IMPORT_BASE):
    """Where a linked module holds placeholder addresses. Takes the two link results of the link-twice method (the module linked at two different load
    addresses) and returns [(offset, index)]: every aligned 32-bit word that holds a placeholder in BOTH, at the same offset, with the same value. A word that holds
    a placeholder in one result only is a bug in the build (it means the word also moved with the base: an address computed from a placeholder) and raises."""
    if len(blob_a) != len(blob_b):
        raise ShellAbiError("the two link results differ in size (%d and %d)" % (len(blob_a), len(blob_b)))
    hi = base + 4 * count
    found = []
    for off in range(0, len(blob_a) - 3, 4):
        a = struct.unpack_from("<I", blob_a, off)[0]
        b = struct.unpack_from("<I", blob_b, off)[0]
        pa = base <= a < hi and (a - base) % 4 == 0
        pb = base <= b < hi and (b - base) % 4 == 0
        if pa != pb or (pa and a != b):
            raise ShellAbiError("offset 0x%X holds %08X in one link and %08X in the other: a placeholder was used in a computation" % (off, a, b))
        if pa:
            found.append((off, (a - base) // 4))
    return found


def patch_imports(blob, imports, addresses):
    """The loader's step, kept here so the tests can run it: writes addresses[index] over every recorded word. Returns the patched copy."""
    out = bytearray(blob)
    for off, index in imports:
        struct.pack_into("<I", out, off, addresses[index] & 0xFFFFFFFF)
    return bytes(out)


# ---------------------------------------------------------------- the header inside a shell module's code
#
# A shell is a plain module (PURR_IMG_MODULE, subtype MOD_SHELL) whose payload is the ordinary module layout (entry offset, data relocations, code relocations,
# code blob: modules.pack_payload), so the kernel's one module loader loads it. What a shell needs on top of that is a fixed-size header that sits at the START
# of the code blob (the linker script puts the section `.shellhdr` first): the loader reads it from the loaded copy.
#
#   word 0   HEADER_MAGIC ("PSHL")
#   word 1   the ABI version the module was built against
#   word 2   the number of exports it was linked against
#   word 3   the bss size: the loader maps that much zeroed memory after the code blob
#   word 4   the number of import sites
#   word 5   reserved (0)
#   then     `export count` pairs (offset into the blob, export index); the first `import sites` pairs are used, the rest are zero.
#
# The size depends only on the export count, so the two link results of the link-twice method have the same layout, and the header is written into both
# after they are linked (it is the same bytes in both, so it is never mistaken for a relocation).

HEADER_MAGIC = 0x4C485350                # "PSHL"
_HEAD_WORDS = 6


def header_size(export_count):
    return 4 * _HEAD_WORDS + 8 * export_count


def build_header(abi_version, export_count, bss_size, imports):
    if len(imports) > export_count:
        raise ShellAbiError("%d import sites but room for %d" % (len(imports), export_count))
    head = struct.pack("<6I", HEADER_MAGIC, abi_version, export_count, bss_size, len(imports), 0)
    pairs = b"".join(struct.pack("<II", off, idx) for off, idx in imports)
    return head + pairs + b"\0" * (8 * (export_count - len(imports)))


def parse_header(blob):
    """The inverse of build_header: a dict with abi_version, export_count, bss_size, imports (a list of (offset, index))."""
    if len(blob) < 4 * _HEAD_WORDS:
        raise ShellAbiError("the code is shorter than a shell header")
    magic, abi, count, bss, nimp, _res = struct.unpack_from("<6I", blob, 0)
    if magic != HEADER_MAGIC:
        raise ShellAbiError("not a shell (header magic %08X)" % magic)
    if nimp > count or len(blob) < header_size(count):
        raise ShellAbiError("the shell header is damaged")
    imports = [struct.unpack_from("<II", blob, 4 * _HEAD_WORDS + 8 * i) for i in range(nimp)]
    return {"abi_version": abi, "export_count": count, "bss_size": bss, "imports": imports}
