"""The shell ABI's list of exports (PurrOS/main/purr_shell_exports.def), as purrstrap needs it to build a loadable shell (plan7.md).

The kernel includes the list as C (purr_shell_abi.c builds the table of real addresses). A shell module is built from ordinary C sources against ordinary
headers, with -mlongcalls, so every call to the OS is `l32r` of a literal followed by `callx8`; the literal is what this module controls: the linker script
made here gives every exported name the placeholder address IMPORT_BASE + 4 * position, so the module's literals hold placeholders, and the loader writes the
real address over each one (the build records where they are with find_imports()). Nothing is mapped at the placeholder addresses on the chip, so a call
that was never patched faults at once instead of running something else.

A name is only ever added at the end of the list; removing or moving one is a new ABI version (purr_shell_abi.h).
"""

import re
import struct

# PURR_SHELL_IMPORT_BASE in purr_shell_abi.h. It is in the same 1 GB region (the top two address bits) as the module's two link addresses (0 and 0x100000):
# the Xtensa windowed `callx8` keeps those bits in the return address, and the linker refuses a call that crosses a region ("windowed longcall crosses 1GB
# boundary"). At run time the module and the kernel are both in the instruction region, so the real calls never cross.
IMPORT_BASE = 0x0F000000
ABI_VERSION = 1                 # PURR_SHELL_ABI_VERSION in purr_shell_abi.h

_LINE = re.compile(r"^\s*SHELL_(FN|DATA)\(\s*(?:([A-Za-z_][A-Za-z0-9_ ]*?)\s*,\s*)?([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*$")


class ShellAbiError(Exception):
    pass


def parse_def(text):
    """The exports in file order: a list of (kind, name, ctype) with kind "fn" or "data" (ctype is None for a function). Comments and blank lines are skipped."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out, seen = [], set()
    for no, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        m = _LINE.match(line)
        if not m:
            raise ShellAbiError("line %d: not SHELL_FN(name) or SHELL_DATA(type, name): %r" % (no, line))
        kind = m.group(1).lower()
        ctype, name = m.group(2), m.group(3)
        if (kind == "data") != (ctype is not None):
            raise ShellAbiError("line %d: SHELL_FN takes a name, SHELL_DATA takes a type and a name: %r" % (no, line))
        if name in seen:
            raise ShellAbiError("line %d: %s is listed twice" % (no, name))
        seen.add(name)
        out.append(("fn" if kind == "fn" else "data", name, ctype))
    if not out:
        raise ShellAbiError("the list is empty")
    return out


def placeholder(index, base=IMPORT_BASE):
    return base + 4 * index


def linker_script(entries, base=IMPORT_BASE):
    """Linker script text that defines every export as its placeholder address (include it with -T next to the module's own script)."""
    lines = ["/* generated by purrstrap/lib/shellabi.py from purr_shell_exports.def: do not edit */"]
    for i, (_kind, name, _ctype) in enumerate(entries):
        lines.append("%s = 0x%08X;" % (name, placeholder(i, base)))
    return "\n".join(lines) + "\n"


def find_imports(blob_a, blob_b, count, base=IMPORT_BASE, skip=None):
    """Where a linked module holds placeholder addresses. Takes the two link results of the link-twice method (the module linked at two different load
    addresses) and returns [(offset, index)]: every aligned 32-bit word that holds a placeholder in BOTH, at the same offset, with the same value. A word that holds
    a placeholder in one result only is a bug in the build (it means the word also moved with the base: an address computed from a placeholder) and raises. `skip` is an
    optional (start, end) range of offsets that is not scanned (the embedded picture pack)."""
    if len(blob_a) != len(blob_b):
        raise ShellAbiError("the two link results differ in size (%d and %d)" % (len(blob_a), len(blob_b)))
    hi = base + 4 * count
    found = []
    for off in range(0, len(blob_a) - 3, 4):
        if skip is not None and skip[0] <= off < skip[1]:
            continue                                         # the shell's own picture pack: data, never code, and a pixel pair could look like a placeholder
        a = struct.unpack_from("<I", blob_a, off)[0]
        b = struct.unpack_from("<I", blob_b, off)[0]
        pa = base <= a < hi and (a - base) % 4 == 0
        pb = base <= b < hi and (b - base) % 4 == 0
        if pa != pb or (pa and a != b):
            raise ShellAbiError("offset 0x%X holds %08X in one link and %08X in the other: a placeholder was used in a computation" % (off, a, b))
        if pa:
            found.append((off, (a - base) // 4))
    return found


def patch_imports(blob, imports, addresses):
    """The loader's step, kept here so the tests can run it: writes addresses[index] over every recorded word. Returns the patched copy."""
    out = bytearray(blob)
    for off, index in imports:
        struct.pack_into("<I", out, off, addresses[index] & 0xFFFFFFFF)
    return bytes(out)


# ---------------------------------------------------------------- the header inside a shell module's code
#
# A shell is a plain module (PURR_IMG_MODULE, subtype MOD_SHELL) whose payload is the ordinary module layout (entry offset, data relocations, code relocations,
# code blob: modules.pack_payload), so the kernel's one module loader loads it. What a shell needs on top of that is a header at the START of the code blob (the
# linker script puts the section `.shellhdr` first). The layout is the one described in PurrOS/components/coreos/include/purr_shellhdr.h:
#
#   word 0 magic, 1 ABI version, 2 bss size, 3 import count, 4 layout count, 5 names size, 6 layout capacity, 7 import capacity, 8 names capacity,
#   bytes 36..51 the kernel version the shell was built against, word 13 the offset of the shell's own picture pack in the code and word 14 its size (0 if it has none),
#   1 reserved word; then layout pairs (id, value), import pairs (offset of the word in the code, offset of the name in the names block), then the names block.
#
# A shell finds the OS names it uses BY NAME (the kernel resolves them against its own export list), and carries the layout facts it was compiled against
# (purr_shell_layout.def); the loader refuses it if one differs. The capacities depend only on the export list and the layout list, so the two link results of
# the link-twice method have the same size, and the header is written into both after they are linked (the same bytes in both, so never mistaken for a relocation).

HEADER_MAGIC = 0x4C485350                # "PSHL"
FIXED = 64
LAYOUT_CAP = 32                          # layout facts a shell may carry (the kernel's list is shorter; the loader refuses a shell with an id it does not know)


def capacities(entries):
    """(layout capacity, import capacity, names capacity in bytes) for a list of exports: room for every export to be used."""
    return LAYOUT_CAP, len(entries), sum(len(name) + 1 for _k, name, _t in entries)


def header_size(caps):
    lcap, icap, ncap = caps
    return FIXED + 8 * lcap + 8 * icap + ((ncap + 3) & ~3)


def build_header(abi_version, built_for, bss_size, imports, layout, caps, pack=(0, 0)):
    """imports: [(offset in the code, name)]; layout: [(id, value)]; pack: (offset in the code, size) of the shell's own picture pack, (0, 0) for none. Raises ShellAbiError if something does not fit the capacities."""
    lcap, icap, ncap = caps
    if len(imports) > icap:
        raise ShellAbiError("%d import sites but room for %d" % (len(imports), icap))
    if len(layout) > lcap:
        raise ShellAbiError("%d layout facts but room for %d" % (len(layout), lcap))
    names, name_off = b"", {}
    for _off, name in imports:
        if name not in name_off:
            name_off[name] = len(names)
            names += name.encode("ascii") + b"\0"
    if len(names) > ncap:
        raise ShellAbiError("the names need %d bytes but room for %d" % (len(names), ncap))
    bf = built_for.encode("ascii")[:16].ljust(16, b"\0")
    head = struct.pack("<9I", HEADER_MAGIC, abi_version, bss_size, len(imports), len(layout), len(names), lcap, icap, ncap) + bf + struct.pack("<III", pack[0], pack[1], 0)
    lay = b"".join(struct.pack("<II", i, v) for i, v in layout) + b"\0" * (8 * (lcap - len(layout)))
    imp = b"".join(struct.pack("<II", off, name_off[name]) for off, name in imports) + b"\0" * (8 * (icap - len(imports)))
    blob = head + lay + imp + names + b"\0" * (((ncap + 3) & ~3) - len(names))
    assert len(blob) == header_size(caps)
    return blob


def parse_header(blob):
    """The inverse of build_header: a dict with abi_version, built_for, bss_size, imports [(offset, name)], layout [(id, value)] and size."""
    if len(blob) < FIXED:
        raise ShellAbiError("the code is shorter than a shell header")
    magic, abi, bss, nimp, nlay, nnames, lcap, icap, ncap = struct.unpack_from("<9I", blob, 0)
    if magic != HEADER_MAGIC:
        raise ShellAbiError("not a shell (header magic %08X)" % magic)
    if nimp > icap or nlay > lcap or nnames > ncap or len(blob) < header_size((lcap, icap, ncap)):
        raise ShellAbiError("the shell header is damaged")
    built_for = blob[36:52].split(b"\0")[0].decode("ascii")
    lay_at = FIXED
    imp_at = lay_at + 8 * lcap
    names_at = imp_at + 8 * icap
    names = blob[names_at:names_at + nnames]
    layout = [struct.unpack_from("<II", blob, lay_at + 8 * i) for i in range(nlay)]
    imports = []
    for i in range(nimp):
        off, noff = struct.unpack_from("<II", blob, imp_at + 8 * i)
        imports.append((off, names[noff:names.index(b"\0", noff)].decode("ascii")))
    pack = struct.unpack_from("<II", blob, 52)
    return {"abi_version": abi, "built_for": built_for, "bss_size": bss, "imports": imports, "layout": layout, "pack": pack, "size": header_size((lcap, icap, ncap))}
