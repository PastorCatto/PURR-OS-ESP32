#!/usr/bin/env python3
"""Writes move_fixture.h: moved.txt files signed by the SDK's Python tooling (sdk/purrsdk/repo.py), so the C parser and rules are checked against what the maintainers' tool writes.

    <python with cryptography> gen_move_fixture.py        (run again only if the format changes; the keys are throwaway and discarded)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", "..", "sdk")))
from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402

from purrsdk import repo  # noqa: E402

OLD = "https://github.com/PastorCatto/PURR-OS-ESP32/releases/download/JumpingJaguar1/recovery.manifest"
OLD_M = "https://github.com/PastorCatto/PURR-OS-ESP32/releases/download/JumpingJaguar2/modules.manifest"
NEW_R = "https://example.org/hub/os/stable/recovery.manifest"
NEW_M = "https://example.org/hub/os/stable/modules.manifest"


def carr(name, data):
    rows = ["    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + "," for i in range(0, len(data), 12)]
    return "static const unsigned char %s[] = {\n%s\n};\nstatic const unsigned %s_len = %d;\n" % (name, "\n".join(rows), name, len(data))


def raw_pub(k):
    n = k.public_key().public_numbers()
    return n.x.to_bytes(32, "big") + n.y.to_bytes(32, "big")


def make(priv, key_id, seq, frm, rec, mod, msg="Updates now come from the PURR hub."):
    text = ("moved=1\nseq=%d\nkey_id=%d\nfrom=%s\nrecovery=%s\nmodules=%s\nmessage=%s\n" % (seq, key_id, frm, rec, mod, msg)).encode()
    return text, repo.sign_bytes(priv, text).hex().encode()


boot = ec.generate_private_key(ec.SECP256R1())
dev = ec.generate_private_key(ec.SECP256R1())
cases = {
    "ok": make(boot, 1, 2, OLD, NEW_R, NEW_M),
    "wrong_from": make(boot, 1, 2, OLD + "x", NEW_R, NEW_M),
    "http": make(boot, 1, 2, OLD, NEW_R.replace("https", "http"), NEW_M),
    "bad_name": make(boot, 1, 2, OLD, NEW_R, "https://example.org/hub/os/stable/index.json"),
    "back": make(boot, 1, 3, NEW_R, OLD, OLD_M),
    "dev_key": make(dev, 2, 2, OLD, NEW_R, NEW_M),
    "unknown_key": make(boot, 9, 2, OLD, NEW_R, NEW_M),
}
text = "/* Generated by gen_move_fixture.py from sdk/purrsdk/repo.py. Do not edit. */\n"
for name, (t, s) in cases.items():
    text += carr("fxm_%s" % name, t) + carr("fxm_%s_sig" % name, s)
text += carr("fxm_boot_pub", raw_pub(boot)) + carr("fxm_dev_pub", raw_pub(dev))
open(os.path.join(HERE, "move_fixture.h"), "w").write(text)
print("wrote move_fixture.h")
