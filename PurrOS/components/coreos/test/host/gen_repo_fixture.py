#!/usr/bin/env python3
"""Writes repo_fixture.h: a repository made by the SDK's Python tooling (sdk/purrsdk/repo.py), so the C code is checked against what the maintainers' tool really writes.

    <python with cryptography> gen_repo_fixture.py        (run again only if the format changes; the keys are throwaway and discarded)
"""
import json
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", "..", "sdk")))
from cryptography.hazmat.primitives import serialization  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402

from purrsdk import formats, repo  # noqa: E402


def carr(name, data):
    rows = ["    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + "," for i in range(0, len(data), 12)]
    return "static const unsigned char %s[] = {\n%s\n};\nstatic const unsigned %s_len = %d;\n" % (name, "\n".join(rows), name, len(data))


def build(endorse):
    d = tempfile.mkdtemp()
    folder = os.path.join(d, "r")
    repo.init(folder, "Fixture Apps", "tests", "https://example.org/fixture", "fixturepw", "made by gen_repo_fixture.py")
    pkg = os.path.join(d, "clock.cat")
    img = formats.image()
    data = img.make_image("clock", "1.2.0", img.IMG_APP, 0, b"clock payload " * 8, img.CHIP_ESP32S3)
    open(pkg, "wb").write(data)
    repo.add(folder, pkg, title="Clock", desc="Tells the time", category="tools", source="https://example.org/clock", perms=["keep-awake"])
    asset = os.path.join(d, "mono.bin")
    open(asset, "wb").write(b"font" * 10)
    repo.add(folder, asset, name="mono-font", version="1.0", type_="asset", dest="fonts/mono.bin", target="any", title="Mono font")
    boot_pub = None
    if endorse:
        boot = ec.generate_private_key(ec.SECP256R1())
        n = boot.public_key().public_numbers()
        boot_pub = n.x.to_bytes(32, "big") + n.y.to_bytes(32, "big")
        kp = os.path.join(d, "boot.key")
        open(kp, "wb").write(boot.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.BestAvailableEncryption(b"bootpw")))
        repo.endorse(folder, kp, 1, "bootpw")
    out = os.path.join(d, "out")
    repo.build(folder, out, "fixturepw", "flat", now=1793300000)
    rd = lambda n: open(os.path.join(out, n), "rb").read()
    return rd("repo.json"), rd("repo.json.sig"), rd("index.json"), rd("index.json.sig"), rd("clock-1.2.0.cat"), boot_pub


c = build(False)
o = build(True)
text = "/* Generated by gen_repo_fixture.py from sdk/purrsdk/repo.py. Do not edit. */\n"
for tag, v in (("comm", c), ("off", o)):
    for nm, b in zip(("repo", "repo_sig", "index", "index_sig", "pkg"), v[:5]):
        text += carr("fx_%s_%s" % (tag, nm), b)
text += carr("fx_boot_pub", o[5])
open(os.path.join(HERE, "repo_fixture.h"), "w").write(text)
print("wrote repo_fixture.h")
