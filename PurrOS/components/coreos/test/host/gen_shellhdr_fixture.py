#!/usr/bin/env python3
"""Writes shellhdr_fixture.h: a shell header and some code as purrstrap's lib/shellabi.py builds them, so the C reader is checked against what the build tool writes.

    python3 gen_shellhdr_fixture.py        (run again only if the header format changes)
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", "..", "purrstrap")))
from lib import shellabi  # noqa: E402

ENTRIES = shellabi.parse_def("SHELL_FN(alpha)\nSHELL_FN(beta)\nSHELL_FN(gamma)\nSHELL_DATA(unsigned, delta)\n")
CAPS = shellabi.capacities(ENTRIES)
HEAD = shellabi.header_size(CAPS)
# code after the header: eight words; words 2 and 5 hold placeholders for "delta" and "alpha", word 0 is an ordinary constant
words = [0x11111111, 0x22222222, shellabi.placeholder(3), 0x33333333, 0x44444444, shellabi.placeholder(0), 0, 0]
imports = [(HEAD + 4 * 2, "delta"), (HEAD + 4 * 5, "alpha")]
layout = [(0, 0x00090200), (1, 7), (2, 24)]
PACK = (HEAD + 4 * len(words), 12)            # a 12-byte "pack" after the eight words
blob = shellabi.build_header(shellabi.ABI_VERSION, "1.0.32", 0x1200, imports, layout, CAPS, pack=PACK) + b"".join(struct.pack("<I", w) for w in words) + b"PACKPACKPACK"
rows = ["    " + ", ".join("0x%02x" % b for b in blob[i:i + 12]) + "," for i in range(0, len(blob), 12)]
with open(os.path.join(HERE, "shellhdr_fixture.h"), "w") as fh:
    fh.write("/* generated by gen_shellhdr_fixture.py from purrstrap/lib/shellabi.py: do not edit */\n")
    fh.write("#define FIXTURE_ABI %d\n#define FIXTURE_HEAD %d\n#define FIXTURE_PACK_OFF %d\n#define FIXTURE_PACK_SIZE %d\n" % (shellabi.ABI_VERSION, HEAD, PACK[0], PACK[1]))
    fh.write("static const unsigned char shell_fixture[] = {\n%s\n};\n" % "\n".join(rows))
print("wrote shellhdr_fixture.h (%d bytes)" % len(blob))
