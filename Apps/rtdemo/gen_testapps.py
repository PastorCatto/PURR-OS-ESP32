#!/usr/bin/env python3
"""Turn a folder of .cat files into PurrOS/main/purr_rt_testapps.c (the app runtime's self-test).

    gen_testapps.py <dir-with-.cat-files> [out.c]

The self-test (CONFIG_PURR_RT_SELFTEST, on in the VM flavor) plants each file at
/apps/<name>/package.cat at boot, so the runtime can be exercised with no transport onto the
device. Build the apps with `purrstrap modules build --kind app`, sign the good ones with the
developer key, leave `rogue.cat` unsigned and flip a byte of `tampered.cat` after signing.
"""
import os
import sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "PurrOS", "main", "purr_rt_testapps.c")
names = sorted(f[:-4] for f in os.listdir(src) if f.endswith(".cat"))
lines = ['/* Generated by Apps/rtdemo/gen_testapps.py. Do not edit. */',
         '#include "purr_rt_selftest.h"', '']
for n in names:
    data = open(os.path.join(src, n + ".cat"), "rb").read()
    lines.append(f"static const uint8_t s_{n}[] = {{")
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
lines.append("const purr_rt_testapp_t purr_rt_testapps[] = {")
for n in names:
    lines.append(f'    {{"{n}", s_{n}, sizeof(s_{n})}},')
lines.append("};")
lines.append(f"const int purr_rt_testapp_count = {len(names)};")
open(out, "w").write("\n".join(lines) + "\n")
print(f"wrote {out}: {len(names)} apps ({', '.join(names)})")
