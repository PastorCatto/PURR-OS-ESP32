#!/usr/bin/env python3
"""Turns a TrueType font into an LVGL 9 font file (the plain, uncompressed bitmap format the built-in Montserrat files use), without Node or lv_font_conv.

    python3 tools/ui/gen_lvgl_font.py --ttf SpaceGrotesk-Bold.ttf --size 92 --bpp 2 --chars "0123456789:" --name tp_font_clock_xl --out PurrOS/main/tpfonts/tp_font_clock_xl.c

It needs freetype-py (`pip install freetype-py`, in a virtual environment: nothing else is touched). The output is a C file that defines `const lv_font_t <name>`;
declare it where it is used (PurrOS/main/purr_tp_fonts.h). The lines and the baseline are taken from the glyphs actually in the font (a digits-only clock font has no
descender, so a label set in it is as tall as its digits), which is what a big clock wants.

--chars is a literal string, or --range 0x20-0x7E, or both. Glyph positions are exact; there is no kerning. See UI/fonts/README.md for where each font came from and its licence.
"""
import argparse
import os
import sys

import freetype


def parse_range(spec):
    out = []
    for part in spec.split(","):
        lo, _, hi = part.partition("-")
        lo = int(lo, 0)
        hi = int(hi, 0) if hi else lo
        out.extend(range(lo, hi + 1))
    return out


def pack(bitmap, bpp):
    """Rows top to bottom, each pixel `bpp` bits, most significant first, rows not padded (as lv_font_conv's no-compress format)."""
    w, h, pitch, buf = bitmap.width, bitmap.rows, bitmap.pitch, bitmap.buffer
    levels = (1 << bpp) - 1
    bits = []
    for y in range(h):
        for x in range(w):
            v = buf[y * pitch + x]
            q = (v * levels + 127) // 255
            bits.append(q)
    out = bytearray()
    acc, n = 0, 0
    for q in bits:
        acc = (acc << bpp) | q
        n += bpp
        if n == 8:
            out.append(acc)
            acc, n = 0, 0
    if n:
        out.append(acc << (8 - n))
    return bytes(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--size", type=int, required=True, help="pixel size (the em)")
    ap.add_argument("--bpp", type=int, default=4, choices=(1, 2, 4, 8))
    ap.add_argument("--chars", default="")
    ap.add_argument("--range", default="")
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--tracking", type=int, default=0, help="extra advance per glyph, in 1/16 px (negative to tighten)")
    a = ap.parse_args()

    cps = sorted(set([ord(c) for c in a.chars] + (parse_range(a.range) if a.range else [])))
    if not cps:
        sys.exit("no characters")
    face = freetype.Face(a.ttf)
    face.set_pixel_sizes(0, a.size)
    glyphs = []
    top, bottom = 0, 0
    for cp in cps:
        face.load_char(chr(cp), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        adv16 = int(round(g.linearHoriAdvance / 65536.0 * 16)) + a.tracking
        glyphs.append({"cp": cp, "w": bm.width, "h": bm.rows, "ofs_x": g.bitmap_left, "ofs_y": g.bitmap_top - bm.rows, "adv": adv16, "data": pack(bm, a.bpp) if bm.width and bm.rows else b""})
        if bm.width and bm.rows:
            top = max(top, g.bitmap_top)
            bottom = max(bottom, bm.rows - g.bitmap_top)
    line_height = top + bottom
    base_line = bottom

    lines = []
    lines.append("/* Generated by tools/ui/gen_lvgl_font.py from %s: %d px, %d bpp, %d glyph(s). Do not edit; see UI/fonts/README.md. */" % (os.path.basename(a.ttf), a.size, a.bpp, len(cps)))
    base = os.path.basename(a.ttf)
    if base.startswith("SpaceMono"):
        lines.append("/* A bitmap rendering of Space Mono Bold, which is licensed under the SIL Open Font License 1.1: UI/fonts/OFL-SpaceMono.txt, THIRD_PARTY.md. */")
    elif base.startswith("SpaceGrotesk"):
        lines.append("/* A bitmap rendering of Space Grotesk Bold, which is licensed under the SIL Open Font License 1.1: UI/fonts/OFL-SpaceGrotesk.txt, THIRD_PARTY.md. */")
    lines.append('#include "lvgl.h"')
    lines.append("")
    lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    index = 0
    for g in glyphs:
        g["index"] = index
        lines.append("    /* U+%04X */" % g["cp"])
        data = g["data"]
        for i in range(0, len(data), 16):
            lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
        index += len(data)
    if index == 0:
        lines.append("    0")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    lines.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for g in glyphs:
        lines.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* U+%04X */" % (g["index"], g["adv"], g["w"], g["h"], g["ofs_x"], g["ofs_y"], g["cp"]))
    lines.append("};")
    lines.append("")
    first, last = cps[0], cps[-1]
    contiguous = last - first + 1 == len(cps)
    if contiguous:
        lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
        lines.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = 1, .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}" % (first, len(cps)))
        lines.append("};")
    else:
        lines.append("static const uint16_t unicode_list_0[] = {%s};" % ", ".join(str(c - first) for c in cps))
        lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
        lines.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = 1, .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}" % (first, last - first + 1, len(cps)))
        lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    lines.append("    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = %d, .kern_classes = 0, .bitmap_format = 0," % a.bpp)
    lines.append("};")
    lines.append("")
    lines.append("const lv_font_t %s = {" % a.name)
    lines.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    lines.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    lines.append("    .line_height = %d," % line_height)
    lines.append("    .base_line = %d," % base_line)
    lines.append("    .subpx = LV_FONT_SUBPX_NONE,")
    lines.append("    .underline_position = -1,")
    lines.append("    .underline_thickness = 2,")
    lines.append("    .dsc = &font_dsc,")
    lines.append("};")
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%s: %d glyph(s), %d bytes of bitmap, line %d, base %d" % (a.name, len(cps), index, line_height, base_line))


if __name__ == "__main__":
    main()
