#!/usr/bin/env python3
"""Renders the PURR OS Mini boot logo (the sitting cat, white on black) to PurrOSMini/main/mini_logo.c: a 4-bit coverage bitmap (0 = black, 15 = white), two pixels a byte, high nibble first.
The picture is original art drawn as the SVG below. Needs rsvg-convert and Pillow."""
import os, subprocess, sys
from PIL import Image

SIZE = 136
SVG = """<svg xmlns="http://www.w3.org/2000/svg" width="170" height="170" viewBox="0 0 170 170">
<rect width="170" height="170" fill="#000"/>
<path d="M52 142 Q40 142 40 128 Q40 100 62 90 Q56 72 64 56 L58 32 L80 46 Q85 44 90 46 L112 32 L106 56 Q114 72 108 90 Q130 100 130 128 Q130 142 118 142 Z" fill="#fff"/>
<path d="M118 138 Q150 136 148 108 Q146 96 136 100" fill="none" stroke="#fff" stroke-width="10" stroke-linecap="round"/>
<circle cx="74" cy="70" r="5" fill="#000"/><circle cx="100" cy="70" r="5" fill="#000"/>
</svg>"""
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "..", "PurrOSMini", "main", "mini_logo.c")
tmp = "/tmp/purr_logo.svg"
open(tmp, "w").write(SVG)
subprocess.run(["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE), tmp, "-o", "/tmp/purr_logo.png"], check=True)
im = Image.open("/tmp/purr_logo.png").convert("L")
px = [min(15, (v + 8) // 17) for v in im.getdata()]
data = []
for i in range(0, len(px), 2):
    data.append((px[i] << 4) | px[i + 1])
with open(out, "w") as f:
    f.write("/* Generated by tools/mini/gen_logo.py: the boot logo, %dx%d, 4 bits a pixel (0 black .. 15 white), high nibble first. Original art. */\n" % (SIZE, SIZE))
    f.write("#include \"mini_logo.h\"\n\nconst int mini_logo_w = %d, mini_logo_h = %d;\nconst unsigned char mini_logo_bits[] = {\n" % (SIZE, SIZE))
    for i in range(0, len(data), 24):
        f.write("    " + ", ".join("0x%02X" % b for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
print("wrote", out, len(data), "bytes")
