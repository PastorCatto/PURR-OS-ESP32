#!/usr/bin/env python3
"""Makes PURR OS Mini's fonts (PurrOSMini/main/mini_fonts.c): ASCII glyphs as 4-bit alpha bitmaps with their metrics, no LVGL needed.

    python3 tools/mini/gen_font.py --bold SourceSans3-Bold.ttf --semibold SourceSans3-Semibold.ttf --regular SourceSans3-Regular.ttf --out PurrOSMini/main/mini_fonts.c

Needs freetype-py (in a virtual environment: pip install freetype-py). Source Sans 3 is under the SIL Open Font License 1.1 (UI/fonts/OFL-SourceSans3.txt, THIRD_PARTY.md)."""
import argparse

import freetype

FONTS = (("mini_font_title", "bold", 20), ("mini_font_row", "semibold", 16), ("mini_font_small", "regular", 12))
FIRST, LAST = 0x20, 0x7E


def build(path, size):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, size)
    glyphs, ascent, descent = [], 0, 0
    for code in range(FIRST, LAST + 1):
        face.load_char(chr(code), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = face.glyph
        bm = g.bitmap
        glyphs.append((bm.width, bm.rows, g.bitmap_left, g.bitmap_top, g.advance.x >> 6, bytes(bm.buffer), bm.pitch))
        if bm.rows:
            ascent = max(ascent, g.bitmap_top)
            descent = max(descent, bm.rows - g.bitmap_top)
    return glyphs, ascent, descent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bold", required=True)
    ap.add_argument("--semibold", required=True)
    ap.add_argument("--regular", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    paths = {"bold": a.bold, "semibold": a.semibold, "regular": a.regular}
    out = ["/* Generated by tools/mini/gen_font.py from Source Sans 3 (SIL Open Font License 1.1: UI/fonts/OFL-SourceSans3.txt). Do not edit. */",
           '#include "mini_gfx.h"', ""]
    total = 0
    for name, weight, size in FONTS:
        glyphs, ascent, descent = build(paths[weight], size)
        bits = bytearray()
        rows = []
        nib = []
        for (w, h, xo, top, adv, buf, pitch) in glyphs:
            off = len(nib) // 2
            for y in range(h):
                for x in range(w):
                    nib.append((buf[y * pitch + x] + 8) // 17)       # 0..255 -> 0..15
            if len(nib) % 2:
                nib.append(0)                                           # each glyph starts on a byte
            rows.append((off, w, h, xo, ascent - top, adv))
        for i in range(0, len(nib), 2):
            bits.append((nib[i] << 4) | nib[i + 1])
        total += len(bits) + len(rows) * 8
        out.append("static const uint8_t %s_bits[] = {" % name)
        for i in range(0, len(bits), 24):
            out.append("    " + ", ".join("0x%02x" % b for b in bits[i:i + 24]) + ",")
        out.append("};")
        out.append("static const mini_glyph_t %s_glyphs[] = {" % name)
        for (off, w, h, xo, yo, adv) in rows:
            out.append("    {%d, %d, %d, %d, %d, %d}," % (off, w, h, xo, yo, adv))
        out.append("};")
        out.append("const mini_font_t %s = {%s_glyphs, %s_bits, 0x%02X, 0x%02X, %d, %d};" % (name, name, name, FIRST, LAST, ascent + descent, ascent))
        out.append("")
    open(a.out, "w").write("\n".join(out) + "\n")
    print("wrote %s (%d bytes of data)" % (a.out, total))


if __name__ == "__main__":
    main()
