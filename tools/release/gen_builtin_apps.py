#!/usr/bin/env python3
"""Writes PurrOS/main/purr_builtin_apps.c: the Store and its companion, built into the firmware so a new account has them at first sign-in, with no network.

    python3 tools/release/gen_builtin_apps.py out/apps/store.cat out/apps/storesvc.cat

They are trusted because they ride inside the signed kernel image (the kernel is checked against the boot key before it runs), so they carry no signature of
their own: the loader accepts them through a receipt that names the built-in table and their hash (purr_store.c). A newer version from the official
repository replaces them like any update. Run this, then rebuild, whenever the Store changes."""
import hashlib
import os
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "purrstrap"))
from lib import image as pimg  # noqa: E402

out = ["/* Generated by tools/release/gen_builtin_apps.py. Do not edit. */",
       '#include "purr_store.h"', ""]
names = []
for path in sys.argv[1:]:
    data = open(path, "rb").read()
    f = pimg.header_fields(pimg.parse_header(data))
    ident = f["name"]
    names.append((ident, f["version"], len(data), hashlib.sha256(data).digest()))
    rows = ["    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    out.append("static const uint8_t k_%s[] = {\n%s\n};\n" % (ident, "\n".join(rows)))
out.append("const purr_builtin_app_t purr_builtin_apps[] = {")
for ident, ver, n, sha in names:
    out.append('    {"%s", "%s", k_%s, %d, {%s}},' % (ident, ver, ident, n, ", ".join("0x%02x" % b for b in sha)))
out.append("};")
out.append("const int purr_builtin_apps_count = %d;" % len(names))
open(os.path.join(ROOT, "PurrOS", "main", "purr_builtin_apps.c"), "w").write("\n".join(out) + "\n")
print("wrote purr_builtin_apps.c:", ", ".join("%s %s (%d bytes)" % (n[0], n[1], n[2]) for n in names))
