// boot_splash.c — raw-framebuffer boot splash
//
// Drawn directly via catcall_display_t (push_pixels/fill_rect), the same
// layer oled_ui uses for its own boot message — deliberately no LVGL, no
// MiniWin dependency, so it works before either UI backend has even
// started, and regardless of which one a given device ends up using.
// Called directly from each device's own boot sequence (e.g.
// kernel_tdp_boot.c), right after the display driver registers — not
// through the P2/P3 static module loader, which only runs much later.
//
// Classic DOS-style "Starting Windows..." look: black background, white
// text, a segmented progress bar. boot_splash_advance() is called once per
// boot phase (see kernel_tdp_boot.c's own "=== phase N ===" markers) —
// there's no hard timeout here; in practice the real UI backend's own
// first full-screen paint (Cupcake or MiniWin, both of which redraw the
// whole display on their first frame) naturally supersedes this before it
// would ever look stale.

